//! The report's Typst body, section by section (mockup row 201, the
//! generated notebook). A section whose source was not read says so and
//! why; nothing is filled in.

use signex_types::check::{CheckReport, Severity};

use super::blocks::{block_fields, label};
use super::facts::{Fact, ProjectFacts};
use super::requirements::{RequirementResult, RequirementRow};
use super::sections::{GenerateOptions, Section};
use super::tables::{bullets, comment_text, counted, listed, paragraph, table};
use crate::annotation::{AnnotationKind, Status};
use crate::reference::quote;
use crate::world::PACKAGE_IMPORT;

/// The most findings a check lists by message; the rest are counted.
pub(super) const LISTED_FINDINGS: usize = 20;

/// The whole Typst body of the report: the import, the layout, the title and
/// the sections `options` names, in report order.
pub(super) fn report_body(
    facts: &ProjectFacts,
    options: &GenerateOptions,
    rows: &[RequirementRow],
) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "// Generated by Signex from {}. Regenerate replaces this whole file;\n\
         // write your own pages in design.snxnbk.\n",
        comment_text(&facts.project_file)
    ));
    out.push_str(PACKAGE_IMPORT);
    out.push('\n');
    let title = format!("{} Design Report", facts.name);
    out.push_str(&format!(
        "#show: report.with(doc: {}, rev: {}, title: {})\n\n",
        optional(options.document.as_deref()),
        optional(options.revision.as_deref()),
        quote(&title)
    ));
    out.push_str(&format!(
        "#align(center, text(size: 17pt, weight: \"bold\", {}))\n",
        quote(&title)
    ));
    out.push_str(&format!(
        "#align(center, text(size: 9pt, {}))\n\n",
        quote(&provenance(facts))
    ));
    for section in options.sections.iter().copied() {
        out.push_str(&format!("= {}\n\n", section.heading()));
        out.push_str(&section_body(section, facts, rows));
        out.push('\n');
    }
    out
}

/// `Some(text)` as a Typst string, `None` as `none`.
fn optional(text: Option<&str>) -> String {
    match text.map(str::trim).filter(|t| !t.is_empty()) {
        Some(text) => quote(text),
        None => "none".to_string(),
    }
}

/// The line under the title: what the report was generated from.
fn provenance(facts: &ProjectFacts) -> String {
    let revision = facts
        .revision
        .as_deref()
        .map(|rev| format!(" rev {rev}"))
        .unwrap_or_default();
    format!(
        "Generated from {}{revision}, variant {}",
        facts.project_file, facts.variant
    )
}

fn section_body(section: Section, facts: &ProjectFacts, rows: &[RequirementRow]) -> String {
    match section {
        Section::Summary => summary(facts, rows),
        Section::Requirements => requirements(facts, rows),
        Section::Architecture => architecture(facts),
        Section::Decisions => decisions(facts),
        Section::Bom => bom(facts),
        Section::Checks => checks(facts),
        Section::Simulation => simulation(facts),
        Section::Outputs => outputs(facts),
        Section::OpenItems => open_items(facts, rows),
        Section::Changelog => changelog(facts),
    }
}

/// What a source that was not read prints in its section.
fn not_read<T>(what: &str, fact: &Fact<T>) -> Option<String> {
    fact.why_not()
        .map(|why| paragraph(&format!("{what} could not be read: {why}.")))
}

fn summary(facts: &ProjectFacts, rows: &[RequirementRow]) -> String {
    let mut out = paragraph(&format!(
        "{} has {} and {}.",
        facts.name,
        counted(facts.sheets.len(), "sheet", "sheets"),
        counted(rows.len(), "requirement", "requirements")
    ));
    out.push_str(&paragraph(&requirement_sentence(rows)));
    out.push_str(&paragraph(&check_sentence(facts)));
    let open = open_issue_labels(facts).len();
    out.push_str(&paragraph(&format!(
        "{} {} open.",
        counted(open, "issue", "issues"),
        if open == 1 { "is" } else { "are" }
    )));
    out
}

/// `Five of six requirements are met.` with the failing ones named.
pub(super) fn requirement_sentence(rows: &[RequirementRow]) -> String {
    let met = rows
        .iter()
        .filter(|r| r.result == RequirementResult::Pass)
        .count();
    let failed: Vec<String> = rows
        .iter()
        .filter(|r| r.result == RequirementResult::Fail)
        .map(|r| r.id.clone())
        .collect();
    let mut line = format!("{met} of {} requirements are met.", rows.len());
    if !failed.is_empty() {
        line.push_str(&format!(" Failing: {}.", failed.join(", ")));
    }
    line
}

/// `ERC: 0 errors, 2 warnings. DRC: 0 errors, 0 warnings.`
fn check_sentence(facts: &ProjectFacts) -> String {
    let one = |name: &str, fact: &Fact<CheckReport>| match fact.value() {
        Some(report) => format!(
            "{name}: {}, {}.",
            counted(severity_count(report, Severity::Error), "error", "errors"),
            counted(
                severity_count(report, Severity::Warning),
                "warning",
                "warnings"
            )
        ),
        None => format!("{name}: not run."),
    };
    format!("{} {}", one("ERC", &facts.erc), one("DRC", &facts.drc))
}

/// The findings of `report` with `severity`.
pub(super) fn severity_count(report: &CheckReport, severity: Severity) -> usize {
    report
        .findings
        .iter()
        .filter(|f| f.severity == severity)
        .count()
}

fn requirements(facts: &ProjectFacts, rows: &[RequirementRow]) -> String {
    if rows.is_empty() {
        return paragraph("The project lists no requirements.");
    }
    let mut out = not_read("The requirement checks", &facts.requirement_check).unwrap_or_default();
    let cells: Vec<Vec<String>> = rows
        .iter()
        .map(|row| {
            vec![
                row.id.clone(),
                row.statement.clone(),
                listed(&row.met_by),
                listed(&row.evidence),
                row.result.word().to_string(),
            ]
        })
        .collect();
    out.push_str(&table(
        "Requirements, design answer and evidence",
        &["Req.", "Statement", "Met by", "Evidence", "Result"],
        &cells,
    ));
    out.push_str(&paragraph(&requirement_sentence(rows)));
    out
}

/// The sheet hierarchy as a block diagram: a box per sheet, indented by its
/// depth, with the power nets that join them.
fn architecture(facts: &ProjectFacts) -> String {
    if facts.sheets.is_empty() {
        return paragraph("The project lists no sheets.");
    }
    let boxes: Vec<String> = facts
        .sheets
        .iter()
        .map(|sheet| {
            format!(
                "    pad(left: {}em, box(stroke: 0.6pt, inset: 6pt, radius: 2pt, [#strong({}) #h(0.6em) #text(size: 8pt, {})])),\n",
                sheet.depth * 2,
                quote(&sheet.name),
                quote(&counted(sheet.parts, "part", "parts"))
            )
        })
        .collect();
    let nets = if facts.power_nets.is_empty() {
        "no power nets".to_string()
    } else {
        format!("power nets {}", facts.power_nets.join(", "))
    };
    let caption = format!("Sheet hierarchy of {} and its {nets}", facts.name);
    format!(
        "#figure(\n  stack(\n    dir: ttb,\n    spacing: 4pt,\n{}  ),\n  caption: {},\n)\n",
        boxes.concat(),
        quote(&caption)
    )
}

/// The accepted Decision blocks, kept as written.
fn decisions(facts: &ProjectFacts) -> String {
    if let Some(line) = not_read("The notebook", &facts.blocks) {
        return line;
    }
    let accepted: Vec<&str> = facts
        .block_list()
        .iter()
        .filter(|b| b.kind == AnnotationKind::Decision && b.status == Some(Status::Accepted))
        .map(|b| b.source.as_str())
        .collect();
    if accepted.is_empty() {
        return paragraph("The notebook records no accepted decisions.");
    }
    let mut out = String::new();
    for source in accepted {
        out.push_str(source.trim());
        out.push_str("\n\n");
    }
    out
}

fn bom(facts: &ProjectFacts) -> String {
    let Some(bom) = facts.bom.value() else {
        return not_read("The BOM", &facts.bom).unwrap_or_default();
    };
    let cost = match &bom.cost {
        Some(cost) => format!(
            "{:.2} {} per board at {} boards",
            cost.per_board, cost.currency, cost.quantity
        ),
        None => "Not priced".to_string(),
    };
    let rows = vec![
        vec!["Lines".to_string(), bom.lines.to_string()],
        vec!["Parts".to_string(), bom.parts.to_string()],
        vec!["Cost".to_string(), cost],
        vec!["No price".to_string(), listed(&bom.unpriced)],
        vec!["No stock".to_string(), listed(&bom.no_stock)],
    ];
    let caption = format!("Bill of materials, variant {}", facts.variant);
    table(&caption, &["", "Value"], &rows)
}

fn checks(facts: &ProjectFacts) -> String {
    let runs = [
        ("ERC", &facts.erc),
        ("DRC", &facts.drc),
        ("Requirements", &facts.requirement_check),
    ];
    let rows: Vec<Vec<String>> = runs
        .iter()
        .map(|(name, fact)| match fact {
            Fact::Read { value, from } => vec![
                name.to_string(),
                severity_count(value, Severity::Error).to_string(),
                severity_count(value, Severity::Warning).to_string(),
                value.waived.len().to_string(),
                from.clone(),
            ],
            Fact::NotRead { why } => vec![
                name.to_string(),
                "—".into(),
                "—".into(),
                "—".into(),
                why.clone(),
            ],
        })
        .collect();
    let mut out = table(
        "ERC, DRC and requirement checks",
        &["Check", "Errors", "Warnings", "Waived", "Run"],
        &rows,
    );
    for (name, fact) in runs {
        let Some(report) = fact.value() else { continue };
        let errors: Vec<String> = report
            .findings
            .iter()
            .filter(|f| f.severity == Severity::Error)
            .map(|f| f.message.clone())
            .collect();
        if errors.is_empty() {
            continue;
        }
        out.push_str(&paragraph(&format!("{name} errors:")));
        out.push_str(&bullets(&clipped(errors)));
    }
    out
}

/// `items` cut to [`LISTED_FINDINGS`], the rest counted in a last item.
fn clipped(mut items: Vec<String>) -> Vec<String> {
    if items.len() > LISTED_FINDINGS {
        let more = items.len() - LISTED_FINDINGS;
        items.truncate(LISTED_FINDINGS);
        items.push(format!("and {more} more"));
    }
    items
}

fn simulation(facts: &ProjectFacts) -> String {
    let Some(runs) = facts.simulation.value() else {
        return not_read("Simulation results", &facts.simulation).unwrap_or_default();
    };
    if runs.is_empty() {
        return paragraph("No simulation runs are recorded for this project.");
    }
    let mut out = String::new();
    for run in runs {
        let rows: Vec<Vec<String>> = run
            .measurements
            .iter()
            .map(|(name, value)| vec![name.clone(), value.clone()])
            .collect();
        let caption = format!("{} ({})", run.name, run.kind);
        out.push_str(&table(&caption, &["Measurement", "Result"], &rows));
    }
    out
}

fn outputs(facts: &ProjectFacts) -> String {
    let Some(files) = facts.outputs.value() else {
        return not_read("The outputs", &facts.outputs).unwrap_or_default();
    };
    if files.is_empty() {
        return paragraph("The last output run wrote no files.");
    }
    let rows: Vec<Vec<String>> = files
        .iter()
        .map(|file| vec![file.path.clone(), file.sha256.clone()])
        .collect();
    table(
        "Files written by the last output run",
        &["File", "SHA-256"],
        &rows,
    )
}

/// The open Issue blocks, by id or title.
pub(super) fn open_issue_labels(facts: &ProjectFacts) -> Vec<String> {
    facts
        .block_list()
        .iter()
        .filter(|b| b.kind == AnnotationKind::Issue && b.status != Some(Status::Resolved))
        .map(label)
        .collect()
}

fn open_items(facts: &ProjectFacts, rows: &[RequirementRow]) -> String {
    let mut items: Vec<String> = facts
        .block_list()
        .iter()
        .filter(|b| b.kind == AnnotationKind::Issue && b.status != Some(Status::Resolved))
        .map(|b| match block_fields(b).id {
            Some(id) if id.to_string() != b.title => format!("{id}: {}", b.title),
            _ => b.title.clone(),
        })
        .collect();
    items.extend(
        rows.iter()
            .filter(|r| r.result == RequirementResult::Fail)
            .map(|r| format!("{} fails: {}", r.id, r.statement)),
    );
    for (name, fact) in [("ERC", &facts.erc), ("DRC", &facts.drc)] {
        let errors = fact
            .value()
            .map_or(0, |r| severity_count(r, Severity::Error));
        if errors > 0 {
            items.push(format!("{name}: {}", counted(errors, "error", "errors")));
        }
    }
    let mut out = not_read("The notebook", &facts.blocks).unwrap_or_default();
    if items.is_empty() {
        out.push_str(&paragraph("Nothing is open."));
    } else {
        out.push_str(&bullets(&items));
    }
    out
}

fn changelog(facts: &ProjectFacts) -> String {
    let Some(changes) = facts.changes.value() else {
        return not_read("The version history", &facts.changes).unwrap_or_default();
    };
    if changes.is_empty() {
        return paragraph("The project has no recorded changes.");
    }
    let rows: Vec<Vec<String>> = changes
        .iter()
        .map(|change| {
            vec![
                change.date.map(|d| d.to_string()).unwrap_or_default(),
                change.revision.clone(),
                change.summary.clone(),
            ]
        })
        .collect();
    table(
        "Project version history",
        &["Date", "Revision", "Change"],
        &rows,
    )
}
