#!/usr/bin/env bash
#
# Edit-tail seam guard (#2326 slice 2, decisions M5 and M6; the wrapper
# exception is issue #2704, ADR-0006). The core half of the schematic edit
# tails lives in crates/signex-app/src/app/state/sheet_change/ until slice 4a
# lifts it.
#
#   callers   The functions of that module visible outside it (any `pub` or
#             `pub(...)` fn but `pub(self)`) are called only from inside the
#             wrapper functions listed in scripts/sheet-change-wrappers.txt
#             (#2704), and by the module itself. A call written inside a macro
#             (`vec![..]`, `assert!(..)`, `format!(..)`) counts too. The list
#             may only shrink: it may hold at most MAX_WRAPPERS lines, and a
#             listed wrapper that no longer calls the core half fails until its
#             line is removed and MAX_WRAPPERS lowered with it. Each wrapper is
#             removed by the slice #2704 names for it.
#   gui_names The module names no GUI state and not the diagnostics log (M6):
#             no `diagnostics`, `ui_state`, `interaction_state`, `panel_ctx` or
#             `window_panel_ctx` identifier. A line for Messages is a Notice.
#
# Both read the code through ast-grep, so comments do not count. Test code is
# left out: files named `tests.rs` or `*_tests.rs`, anything under a `tests/`
# or `*_tests/` folder, and items under `#[cfg(test)]`.
#
# Blind spots: a call through a renamed import (`use ...::settle_sheet_at as
# s`) or a function pointer passes; the function list is read from `fn` items,
# so a method generated by a macro is not guarded; a wrapper is named by file
# and fn name, so a second fn of that name in that file counts too; inside a
# macro any token with a core function's name counts as a call.
#
# Usage: scripts/check_sheet_change_seam.sh   (SHEET_CHANGE_SEAM_ROOT
# overrides the tree, for scripts/test_check_sheet_change_seam.sh)
set -euo pipefail

# The most lines scripts/sheet-change-wrappers.txt may hold (#2704). Lower it
# when a wrapper goes; never raise it.
MAX_WRAPPERS="${SHEET_CHANGE_SEAM_MAX:-9}"

ROOT="${SHEET_CHANGE_SEAM_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
NAMES_RULE="$(cd "$(dirname "$0")" && pwd)/sheet-change-seam.yml"
LIST="scripts/sheet-change-wrappers.txt"
APP="crates/signex-app/src/app"
CORE="$APP/state/sheet_change"

cd "$ROOT"
for tool in ast-grep jq; do
  if ! command -v "$tool" >/dev/null 2>&1; then
    echo "Sheet-change seam guard: FAIL — $tool is not installed."
    exit 2
  fi
done
if [[ ! -d "$CORE" || ! -f "$LIST" ]]; then
  echo "Sheet-change seam guard: FAIL — no $CORE or $LIST under $ROOT."
  exit 2
fi

# Matches outside test files (jq filter on ast-grep JSON).
PRODUCTION='.[]
  | select(.file | test("(^|/|_)tests/|(^|/|_)tests\\.rs$") | not)'
NOT_IN_TEST='
  not:
    inside:
      stopBy: end
      any:
        - kind: mod_item
        - kind: function_item
        - kind: impl_item
      follows:
        stopBy:
          not:
            any:
              - kind: attribute_item
              - kind: line_comment
              - kind: block_comment
        pattern: "#[cfg(test)]"'
FN_NAME='capture("fn\\s+(?<n>[A-Za-z_][A-Za-z0-9_]*)").n'

fail=0
listed="$(grep -vE '^[[:space:]]*(#|$)' "$LIST" | tr -s ' \t' ' ' | sed 's/^ //; s/ $//' | sort -u)"
count="$(printf '%s\n' "$listed" | grep -c . || true)"
if (( count > MAX_WRAPPERS )); then
  echo "Sheet-change seam guard: FAIL — $LIST lists $count wrappers, at most $MAX_WRAPPERS (#2704)."
  echo "  The list may only shrink: call an existing wrapper instead of adding one."
  fail=1
elif (( count < MAX_WRAPPERS )); then
  echo "Sheet-change seam guard: FAIL — $LIST lists $count wrappers; lower MAX_WRAPPERS in $0 to $count."
  fail=1
fi

# The fn names of the core module visible outside it.
if ! decls="$(ast-grep scan --json=compact --inline-rules "
id: sheet-change-visible-fn
language: rust
rule:
  kind: function_item
  has:
    kind: visibility_modifier
    regex: '^pub'
    not:
      regex: '^pub\\(\\s*self\\s*\\)\$'
$NOT_IN_TEST" "$CORE")"; then
  echo "Sheet-change seam guard: FAIL — ast-grep could not list $CORE's functions."
  exit 2
fi
names="$(jq -r "$PRODUCTION | .text | $FN_NAME" <<<"$decls" | sort -u | paste -sd '|' -)"

if [[ -n "$names" ]]; then
  # A call, or the name as a token inside a macro's token tree.
  USE="any:
      - {kind: call_expression, has: {field: function, regex: '(^|[.:])($names)\$'}}
      - {kind: identifier, regex: '^($names)\$', inside: {kind: token_tree, stopBy: end}}"
  if ! uses="$(ast-grep scan --json=compact --inline-rules "
id: sheet-change-use
language: rust
rule:
  all:
    - $USE
  $NOT_IN_TEST" crates)" || ! callers="$(ast-grep scan --json=compact --inline-rules "
id: sheet-change-caller
language: rust
rule:
  kind: function_item
  has:
    stopBy: end
    $USE" crates)"; then
    echo "Sheet-change seam guard: FAIL — ast-grep could not scan the calls."
    exit 2
  fi
  # Listed wrappers as {file, name, start, end} line ranges.
  allowed="$(jq -c --arg app "$APP/" --arg listed "$listed" "[$PRODUCTION
    | {file: (.file | ltrimstr(\$app)), name: (.text | $FN_NAME),
       start: (.range.start.line + 1), end: (.range.end.line + 1)}
    | select((\"\(.file) \(.name)\") as \$k | \$listed | split(\"\n\") | index(\$k))]" <<<"$callers")"
  outside="$(jq -r --arg core "$CORE/" --arg app "$APP/" --argjson allowed "$allowed" "$PRODUCTION
    | select(.file | startswith(\$core) | not)
    | (.file | ltrimstr(\$app)) as \$f | (.range.start.line + 1) as \$l
    | select([\$allowed[] | select(.file == \$f and .start <= \$l and \$l <= .end)] | length == 0)
    | \"\(.file):\(\$l): \(.text | split(\"\n\")[0])\"" <<<"$uses" | sort -u)"
  if [[ -n "$outside" ]]; then
    echo "Sheet-change seam guard: FAIL — the core half of the edit tails is called outside its wrappers (#2704):"
    printf '%s\n' "$outside" | awk '{ print "  " $0 }'
    echo "  Call a listed wrapper (apply_engine_command*, execute_on_sheet, after_sheet_change, ...) instead."
    fail=1
  fi
  live="$(jq -r '.[] | "\(.file) \(.name)"' <<<"$allowed" | sort -u)"
  stale="$(comm -23 <(printf '%s\n' "$listed") <(printf '%s\n' "$live") | sed '/^$/d')"
  if [[ -n "$stale" ]]; then
    echo "Sheet-change seam guard: FAIL — listed wrappers no longer call the core half; remove their lines from $LIST:"
    printf '%s\n' "$stale" | awk '{ print "  " $0 }'
    fail=1
  fi
fi

if ! named="$(ast-grep scan --rule "$NAMES_RULE" --json=compact "$CORE")"; then
  echo "Sheet-change seam guard: FAIL — ast-grep could not run $NAMES_RULE."
  exit 2
fi
gui="$(jq -r "$PRODUCTION"' | "\(.file):\(.range.start.line + 1): \(.text)"' <<<"$named" | sort)"
if [[ -n "$gui" ]]; then
  echo "Sheet-change seam guard: FAIL — $CORE names GUI state or the diagnostics log:"
  printf '%s\n' "$gui" | awk '{ print "  " $0 }'
  echo "  Return a CoreEvent (a Notice for Messages) and let app/projector act on it (#2326 M6)."
  fail=1
fi

if (( fail )); then
  exit 1
fi
echo "Sheet-change seam guard: OK — the core half is called only by the $count listed wrappers (#2704); no GUI names in $CORE."
